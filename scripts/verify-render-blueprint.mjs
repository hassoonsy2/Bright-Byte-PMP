import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const blueprintPath = resolve(process.cwd(), "render.yaml");
const source = readFileSync(blueprintPath, "utf8");
const lines = source.split(/\r?\n/);
const failures = [];

const serviceNames = [
  "bright-byte-api",
  "bright-byte-worker",
  "bright-byte-beat",
  "bright-byte-live",
  "bright-byte-space",
  "bright-byte-web",
  "bright-byte-admin",
  "bright-byte-redis",
];

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function fail(message) {
  failures.push(message);
}

function countNameEntries(name) {
  const pattern = new RegExp(`^\\s*name:\\s*${escapeRegex(name)}\\s*$`, "gm");
  return source.match(pattern)?.length ?? 0;
}

function findTopLevelItemBlock(name) {
  const namePattern = new RegExp(`^\\s*name:\\s*${escapeRegex(name)}\\s*$`);
  const nameIndex = lines.findIndex((line) => namePattern.test(line));

  if (nameIndex === -1) {
    return "";
  }

  let start = nameIndex;
  while (start > 0 && !/^\s{2}-\s+/.test(lines[start])) {
    start -= 1;
  }

  const itemIndent = lines[start].match(/^(\s*)-\s+/)?.[1] ?? "";
  let end = lines.length;

  for (let index = start + 1; index < lines.length; index += 1) {
    if (lines[index].startsWith(`${itemIndent}- `)) {
      end = index;
      break;
    }
  }

  return lines.slice(start, end).join("\n");
}

function findEnvVarBlock(serviceBlock, key) {
  const blockLines = serviceBlock.split(/\r?\n/);
  const keyPattern = new RegExp(`^\\s*-\\s+key:\\s*${escapeRegex(key)}\\s*$`);
  const keyIndex = blockLines.findIndex((line) => keyPattern.test(line));

  if (keyIndex === -1) {
    return "";
  }

  const itemIndent = blockLines[keyIndex].match(/^(\s*)-\s+key:/)?.[1] ?? "";
  let end = blockLines.length;

  for (let index = keyIndex + 1; index < blockLines.length; index += 1) {
    if (blockLines[index].startsWith(`${itemIndent}- key:`)) {
      end = index;
      break;
    }
  }

  return blockLines.slice(keyIndex, end).join("\n");
}

function fieldValue(block, field) {
  const pattern = new RegExp(`^\\s*(?:-\\s+)?${escapeRegex(field)}:\\s*(.+?)\\s*$`, "m");
  return block.match(pattern)?.[1]?.trim() ?? "";
}

function expectContains(block, value, message) {
  if (!block.includes(value)) {
    fail(message);
  }
}

function expectNotContains(block, value, message) {
  if (block.includes(value)) {
    fail(message);
  }
}

function expectEnvFromDatabase(serviceName, key, databaseName) {
  const block = findTopLevelItemBlock(serviceName);
  const envBlock = findEnvVarBlock(block, key);

  if (!envBlock) {
    fail(`${serviceName} is missing ${key}`);
    return;
  }

  expectContains(envBlock, "fromDatabase:", `${serviceName}.${key} must use fromDatabase`);
  expectContains(envBlock, `name: ${databaseName}`, `${serviceName}.${key} must reference ${databaseName}`);
  expectContains(envBlock, "property: connectionString", `${serviceName}.${key} must use connectionString`);
}

function expectEnvFromService(serviceName, key, serviceType, targetServiceName) {
  const block = findTopLevelItemBlock(serviceName);
  const envBlock = findEnvVarBlock(block, key);

  if (!envBlock) {
    fail(`${serviceName} is missing ${key}`);
    return;
  }

  expectContains(envBlock, "fromService:", `${serviceName}.${key} must use fromService`);
  expectContains(envBlock, `type: ${serviceType}`, `${serviceName}.${key} must reference ${serviceType}`);
  expectContains(envBlock, `name: ${targetServiceName}`, `${serviceName}.${key} must reference ${targetServiceName}`);
  expectContains(envBlock, "property: connectionString", `${serviceName}.${key} must use connectionString`);
}

function expectEnvFromApi(serviceName, key) {
  const block = findTopLevelItemBlock(serviceName);
  const envBlock = findEnvVarBlock(block, key);

  if (!envBlock) {
    fail(`${serviceName} is missing ${key}`);
    return;
  }

  expectContains(envBlock, "fromService:", `${serviceName}.${key} must use fromService`);
  expectContains(envBlock, "type: web", `${serviceName}.${key} must reference the API web service`);
  expectContains(envBlock, "name: bright-byte-api", `${serviceName}.${key} must reference bright-byte-api`);
  expectContains(envBlock, `envVarKey: ${key}`, `${serviceName}.${key} must sync the API env var`);
}

function expectGeneratedEnv(serviceName, key) {
  const block = findTopLevelItemBlock(serviceName);
  const envBlock = findEnvVarBlock(block, key);

  if (!envBlock) {
    fail(`${serviceName} is missing ${key}`);
    return;
  }

  expectContains(envBlock, "generateValue: true", `${serviceName}.${key} must be generated by Render`);
}

function expectPlanNotFree(block, name) {
  if (/^\s*plan:\s*free\s*$/im.test(block)) {
    fail(`${name} must not use Render's free plan`);
  }
}

for (const name of serviceNames) {
  if (countNameEntries(name) === 0) {
    fail(`render.yaml is missing ${name}`);
  }
}

if (countNameEntries("bright-byte-postgres") === 0) {
  fail("render.yaml is missing bright-byte-postgres");
}

if (countNameEntries("bright-byte-beat") !== 1) {
  fail("render.yaml must declare exactly one bright-byte-beat scheduler");
}

const beatCommandCount = source.match(/docker-entrypoint-beat\.sh/g)?.length ?? 0;
if (beatCommandCount !== 1) {
  fail("render.yaml must reference docker-entrypoint-beat.sh exactly once");
}

const postgresBlock = findTopLevelItemBlock("bright-byte-postgres");
const redisBlock = findTopLevelItemBlock("bright-byte-redis");
const apiBlock = findTopLevelItemBlock("bright-byte-api");
const workerBlock = findTopLevelItemBlock("bright-byte-worker");
const beatBlock = findTopLevelItemBlock("bright-byte-beat");
const liveBlock = findTopLevelItemBlock("bright-byte-live");
const spaceBlock = findTopLevelItemBlock("bright-byte-space");
const webBlock = findTopLevelItemBlock("bright-byte-web");
const adminBlock = findTopLevelItemBlock("bright-byte-admin");

expectPlanNotFree(postgresBlock, "bright-byte-postgres");
expectPlanNotFree(redisBlock, "bright-byte-redis");

if (fieldValue(redisBlock, "type") !== "keyvalue") {
  fail("bright-byte-redis must be a Render Key Value service");
}

if (fieldValue(redisBlock, "maxmemoryPolicy") !== "noeviction") {
  fail("bright-byte-redis must use maxmemoryPolicy: noeviction");
}

expectContains(apiBlock, "runtime: docker", "bright-byte-api must use Docker runtime");
expectContains(
  apiBlock,
  "dockerfilePath: ./apps/api/Dockerfile.api",
  "bright-byte-api must use apps/api/Dockerfile.api"
);
expectContains(apiBlock, "dockerContext: ./apps/api", "bright-byte-api must use apps/api as Docker context");
expectContains(
  apiBlock,
  "preDeployCommand: ./bin/docker-entrypoint-migrator.sh",
  "bright-byte-api must run the migrator pre-deploy command"
);

expectContains(workerBlock, "runtime: docker", "bright-byte-worker must use Docker runtime");
expectContains(
  workerBlock,
  "dockerfilePath: ./apps/api/Dockerfile.api",
  "bright-byte-worker must use apps/api/Dockerfile.api"
);
expectContains(workerBlock, "dockerContext: ./apps/api", "bright-byte-worker must use apps/api as Docker context");
expectContains(
  workerBlock,
  "dockerCommand: ./bin/docker-entrypoint-worker.sh",
  "bright-byte-worker must run the worker entrypoint"
);

expectContains(beatBlock, "runtime: docker", "bright-byte-beat must use Docker runtime");
expectContains(
  beatBlock,
  "dockerfilePath: ./apps/api/Dockerfile.api",
  "bright-byte-beat must use apps/api/Dockerfile.api"
);
expectContains(beatBlock, "dockerContext: ./apps/api", "bright-byte-beat must use apps/api as Docker context");
expectContains(
  beatBlock,
  "dockerCommand: ./bin/docker-entrypoint-beat.sh",
  "bright-byte-beat must run the beat entrypoint"
);
expectContains(beatBlock, "numInstances: 1", "bright-byte-beat must run as a single scheduler instance");

expectContains(liveBlock, "runtime: docker", "bright-byte-live must use Docker runtime");
expectContains(
  liveBlock,
  "dockerfilePath: ./apps/live/Dockerfile.live",
  "bright-byte-live must use apps/live/Dockerfile.live"
);

expectContains(spaceBlock, "runtime: docker", "bright-byte-space must use Docker runtime");
expectContains(
  spaceBlock,
  "dockerfilePath: ./apps/space/Dockerfile.space",
  "bright-byte-space must use apps/space/Dockerfile.space"
);

for (const [serviceName, block] of [
  ["bright-byte-web", webBlock],
  ["bright-byte-admin", adminBlock],
]) {
  expectContains(block, "runtime: static", `${serviceName} must use Render static runtime`);
  expectNotContains(block, "dockerfilePath:", `${serviceName} must not declare a Dockerfile`);
  expectNotContains(block, "dockerContext:", `${serviceName} must not declare a Docker context`);
}

for (const serviceName of ["bright-byte-api", "bright-byte-worker", "bright-byte-beat"]) {
  expectEnvFromDatabase(serviceName, "DATABASE_URL", "bright-byte-postgres");
  expectEnvFromService(serviceName, "REDIS_URL", "keyvalue", "bright-byte-redis");
  expectEnvFromService(serviceName, "CELERY_BROKER_URL", "keyvalue", "bright-byte-redis");
}

expectGeneratedEnv("bright-byte-api", "SECRET_KEY");
expectGeneratedEnv("bright-byte-api", "LIVE_SERVER_SECRET_KEY");

for (const serviceName of ["bright-byte-worker", "bright-byte-beat"]) {
  expectEnvFromApi(serviceName, "SECRET_KEY");
  expectEnvFromApi(serviceName, "LIVE_SERVER_SECRET_KEY");
}

expectEnvFromService("bright-byte-live", "REDIS_URL", "keyvalue", "bright-byte-redis");
expectEnvFromApi("bright-byte-live", "LIVE_SERVER_SECRET_KEY");

const suspiciousSecretPattern = /(AKIA|aws_secret_access_key|secret-key|access-key|password\s*:)/i;
if (suspiciousSecretPattern.test(source)) {
  fail("render.yaml appears to contain a literal credential or secret-like value");
}

if (failures.length > 0) {
  console.error("render.yaml topology verification failed:");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  process.exit(1);
}

console.log("render.yaml topology verification passed");
